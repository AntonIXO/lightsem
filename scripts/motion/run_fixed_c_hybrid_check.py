"""Human-check composition of verified fixed C with D4-max and external D6.

No neural training/inference change. Every gesture comes from the own-song
repaired HF16 trajectory. Numerical failures remain labeled diagnostics.
"""
from pathlib import Path
import argparse
import json
import shutil

import numpy as np
from lightsem.experiments.dynamic_dance.contracts import DanceResult, MusicTimeline
from lightsem.experiments.dynamic_dance_combo.campaign import arrays, save, read, sha, _save_composed, map_one
from lightsem.experiments.d4max_d8.motifs import Config, build_bank, compose
from lightsem.experiments.d4max.pacing import apply_d6
from lightsem.experiments.native_repair.assessment import raw_metrics
from scripts.rendering import render_native_dynamics as render_base


def verify(root):
    plan = read(root / 'PLAN.json')
    for filename, expected in plan['files'].items():
        if sha(filename) != expected:
            raise ValueError('Changed frozen input: ' + filename)
    if plan['transfer']['apply_motion_limits'] or plan['preview_3d']['fixture_motion_limits']:
        raise ValueError('Fixture motion limits must stay off')
    if shutil.disk_usage(root).free < plan['minimum_free_bytes'] + 16 * 2 ** 20:
        raise ValueError('20GiB reserve reached')
    return plan


def generate(root, song):
    plan = verify(root)
    track = next(t for t in plan['tracks'] if t['id'] == song)
    source_path = root / 'bodies/D7_reference' / song / 'body.npz'
    source = DanceResult.load(source_path)
    fixed = plan['preview_3d']['fixed_native_sources'][song]
    if sha(source_path) != fixed['body_sha256'] or sha(source_path.with_suffix('.json')) != fixed['metadata_sha256']:
        raise ValueError('Wrong fixed native-C source')
    if source.metadata['checkpoint']['sha256'] != plan['source_checkpoint_sha256']:
        raise ValueError('Body is not generated by the qualified HF16 checkpoint')
    music = MusicTimeline.load(track['music_timeline'])
    cfg = Config(**{k: v for k, v in plan['d4max'].items() if k in Config.__dataclass_fields__})
    bank = build_bank(source.world, music, cfg)
    folder = root / 'banks' / song
    arrays(folder / 'features.npz', features=bank['features'], labels=bank['labels'], medoids=bank['medoids'], **bank['feature_reference'])
    save(folder / 'BANK.json', {k: v for k, v in bank.items() if k not in ('features', 'labels', 'medoids', 'feature_reference')})
    with np.load(track['local_plan_telemetry'], allow_pickle=False) as data:
        telemetry = {k: data[k].copy() for k in data.files}
    d4, d4plan, _ = compose(source.world, music, cfg, bank=bank)
    common = {'generated_source': str(source_path), 'generated_source_sha256': sha(source_path),
              'generation_provenance': source.metadata, 'newly_generated_motion': False,
              'source_library_label': 'FIXED_NATIVE_C_HF16', 'motif_recomposition': True,
              'source_body_used': True, 'music_timeline': track['music_timeline'],
              'music_timeline_sha256': sha(track['music_timeline']), 'no_additional_D7_or_D8_model': True,
              'quiet_gradient_fix_in_checkpoint': False}
    d4path = _save_composed(root, 'C3', song, d4, d4plan, source_path,
                           {**common, 'components': ['fixed_native_C', 'D4_max'], 'd6_enabled': False,
                            'retiming': True, 'source_order_preserved': False,
                            'motion_origin': 'Own-song repaired native-C fragments recomposed by D4-max'})
    combo, combo_plan, proposals = apply_d6(d4, d4plan, telemetry, music, minimum_rate=.25)
    extra = {**common, 'components': ['fixed_native_C', 'D4_max', 'D6_positive_anchored'],
             'd6_enabled': True, 'retiming': True, 'source_order_preserved': True,
             'original_library_source_order_preserved': False,
             'd4_plan': str(d4path.parent / 'plan.npz'), 'd4_plan_sha256': sha(d4path.parent / 'plan.npz'),
             'planner_telemetry': track['local_plan_telemetry'], 'planner_telemetry_sha256': sha(track['local_plan_telemetry']),
             'motion_origin': 'D4-max own-song repaired-C motif recomposition plus external frozen D6 pacing',
             'fragment_clock_domain': 'D4-only composition; original fragment jumps recorded separately',
             'learned_native_speed_change': False}
    result_path = _save_composed(root, 'C4', song, combo, combo_plan, d4path, extra)
    arrays(result_path.parent / 'rate_proposals.npz', time=combo.time, desired_rates=proposals)
    repeated, repeated_plan, _ = apply_d6(d4, d4plan, telemetry, music, minimum_rate=.25)
    if not np.array_equal(repeated.world, combo.world) or not np.array_equal(repeated_plan.source_time, combo_plan.source_time):
        raise ValueError('Composition repeat differs')
    controls = {}
    shifted, _, _ = apply_d6(d4, d4plan, telemetry, music, control='shift', minimum_rate=.25)
    controls['D6_shift'] = shifted.world
    shuffled, shuffled_plan, _ = compose(source.world, music, cfg, bank=bank, control='shuffle')
    other, _, _ = apply_d6(shuffled, shuffled_plan, telemetry, music, minimum_rate=.25)
    controls['D4_shuffle'] = other.world
    donor = track['waveform_controls']['donor']
    donor_music = MusicTimeline.load(donor['music_timeline'])
    with np.load(donor['local_plan_telemetry'], allow_pickle=False) as data:
        donor_telemetry = {k: data[k].copy() for k in data.files}
    other, other_plan, _ = compose(source.world, music, cfg, bank=bank, target_music=donor_music)
    donor_result, _, _ = apply_d6(other, other_plan, donor_telemetry, donor_music, minimum_rate=.25)
    controls['donor_query'] = donor_result.world
    frozen = np.broadcast_to(source.world[90 * 30], source.world.shape).copy()
    frozen_d4, frozen_plan, _ = compose(frozen, music, cfg)
    frozen_result, _, _ = apply_d6(frozen_d4, frozen_plan, telemetry, music, minimum_rate=.25)
    if not np.array_equal(frozen_result.world, frozen.astype(np.float32)):
        raise ValueError('Frozen source created autonomous dance')
    measured = {}
    for scope, interval in (('full_song', (0., track['duration_s'])), ('90_150', (90., 150.))):
        mask = (source.time >= interval[0]) & (source.time < interval[1])
        measured[scope] = {name: raw_metrics(world[mask], source.world[mask])
                           for name, world in (('fixed_C', source.world), ('D4_only', d4.world), ('D4_D6', combo.world))}
    status = {'repeat_exact': True, 'frozen_source_exact': True,
              'controller_changes': {name: {'world_RMS_difference_m': float(np.sqrt(np.mean((world - combo.world) ** 2))),
                                             'exactly_equal': bool(np.array_equal(world, combo.world))}
                                     for name, world in controls.items()},
              'body_exactly_equal_to_fixed_C': bool(np.array_equal(source.world, combo.world)),
              'D4_body_exactly_equal_to_fixed_C': bool(np.array_equal(source.world, d4.world)),
              'D4_fragments_recomposed': d4.metadata['recomposed_fragment_count'],
              'D4_fragment_count': d4.metadata['graph_node_count'],
              'D6_minimum_actual_rate': float(combo_plan.effort.min()), 'D6_maximum_actual_rate': float(combo_plan.effort.max()),
              'D6_motif_anchor_error_s': combo_plan.metadata['pacing']['anchor_max_error_s']}
    # Finite diagnostics may be delivered. These predeclared engineering gates
    # determine the warning, never seed selection or a substitute trajectory.
    failures = []
    for scope, rows in measured.items():
        candidate, reference = rows['D4_D6'], rows['fixed_C']
        for name, factor in (('raw_relative_jerk_p95_m_s3', 1.0), ('high_frequency_residual_RMS_m', 1.25),
                             ('root_vertical_fast_residual_RMS_m', 1.25), ('geometric_slide_p95_m_s', 1.10)):
            if candidate[name] > factor * max(reference[name], 1e-12):
                failures.append(scope + ':' + name)
        if not candidate['finite'] or candidate['constant_body']:
            raise ValueError('Broken/nonfinite/inactive composition; preserve artifacts')
        if candidate['low_frequency_speed_spread_m_s'] < .8 * reference['low_frequency_speed_spread_m_s']:
            failures.append(scope + ':speed_variation')
    save(root / 'reports' / (song + '_ADMISSION.json'),
         {'scope': 'Finite human-check diagnostic, not qualification of native training or musical superiority',
          'status': 'failure_diagnostic' if failures else 'human_check_unqualified', 'failure_reasons': failures,
          'raw_metrics': measured, 'composition': status, 'source_body': str(source_path), 'source_body_sha256': sha(source_path),
          'candidate_body_sha256': sha(result_path), 'plan_sha256': sha(root / 'PLAN.json'),
          'controls_scope': 'Same fixed own-song body; modifier audio paths replaced/reused from authenticated interventions. Not a new generator audio-sensitivity test.'})
    for method in ('C3', 'C4'):
        map_one(root, song, method)
    save(root / 'reports' / (song + '_GENERATED.json'), {'inputs_verified': True, 'composition': status, 'mapped': ['C3', 'C4']})
    print(json.dumps({'song': song, 'composition': status, 'failure_reasons': failures}, indent=2))


def preflight(root):
    from scripts.rendering.native_unlimited_emission import generate as emit, apply as actual
    from lightsem.experiments.d4max_d8.source_checks import source_checks
    from lightsem.experiments.dynamic_dance.diagnostics import emission_diagnostics, duplicate_streams
    plan = verify(root)
    emit(root)
    rows = []
    for track in plan['tracks']:
        song = track['id']
        source_checks(root, song)
        for method in ('D7_reference', 'C3', 'C4'):
            pair = actual(root, method, song, render_base.load_pair(root, plan, method, track))
            moving = np.asarray([p['kind'] != 'bulb' for p in pair.patch])
            with np.load(root / 'timelines' / method / song / 'timeline.npz', allow_pickle=False) as data:
                vector = data['targets'][:, moving] - np.asarray([p['position'] for p in pair.patch])[moving]
            length = np.linalg.norm(vector, axis=-1)
            requested = np.stack((np.rad2deg(np.arctan2(vector[..., 0], -vector[..., 1])),
                                  np.rad2deg(np.arcsin(np.clip(vector[..., 2] / length, -1, 1)))), -1)
            metrics = emission_diagnostics(requested, pair.controls['angles_deg'][:, moving], pair.times)
            metrics['speed_acceleration_threshold_scope'] = 'Historical90/360 reference counts only; fixture caps are OFF, so these are not actuator saturation gates.'
            metrics['exact_motion_stream_duplicates'] = duplicate_streams(pair.controls['angles_deg'][:, moving])
            if not all(np.isfinite(v).all() for v in pair.controls.values()):
                raise ValueError('Nonfinite emitted output')
            rgb = np.rint(pair.controls['rgb'] * 255).astype(np.uint8)
            palette_changes = int(np.any(rgb[1:] != rgb[:-1], axis=(1, 2)).sum())
            with np.load(root / 'colors' / song / 'P2.npz', allow_pickle=False) as color:
                color_cues = int(np.asarray(color['color_cues10']).sum())
                occupancy = {str(int(k)): int(v) for k, v in zip(*np.unique(color['palette_ids40'], return_counts=True))}
            rows.append({'song': song, 'method': method, 'emission': metrics,
                         'color_cues': color_cues, 'actual_RGB_transition_ticks': palette_changes, 'palette_occupancy': occupancy,
                         'brightness': {'minimum': float(pair.controls['dimmer'].min()), 'maximum': float(pair.controls['dimmer'].max()),
                                        'mean': float(pair.controls['dimmer'].mean())},
                         'body_sha256': pair.pins['body_sha256'], 'unlimited_emission_sha256': pair.pins['unlimited_emission_sha256']})
    save(root / 'reports/MEDIA_PREFLIGHT.json', {'status': 'finite_diagnostics_ready_for_smoke', 'rows': rows,
                                              'source_count_controls_passed': True, 'fixture_motion_caps': False})
    print('PREFLIGHT_COMPLETE')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action', choices=('generate', 'preflight'))
    parser.add_argument('--root', type=Path, required=True)
    parser.add_argument('--plan-sha256', required=True)
    parser.add_argument('--song', choices=('shpongle', 'cure_for_me'))
    args = parser.parse_args()
    if sha(args.root / 'PLAN.json') != args.plan_sha256:
        raise ValueError('PLAN identity differs')
    if args.action == 'generate':
        generate(args.root, args.song)
    else:
        preflight(args.root)
